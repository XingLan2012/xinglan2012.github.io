/** 由紧凑表展开成完整条目 */
export function buildCometEntries() {
  return COMETS.map((r, i) => {
    const [id, zh, en, a, e, inc, nucleusKm, periodYr, year, cls, note] = r;
    /* 星际天体是双曲轨道（a < 0、e > 1），开普勒椭圆解算会在这里发散
       （1 + e·cosν 会过零，半径冲到 10¹⁵ AU）。改用一个「等效椭圆」：
       保持近日点距离 q 不变，把偏心率压到 0.995，于是 a = q / 0.005。
       轨道在近日点附近与实际几乎重合，且不会发散。 */
    const q = a * (1 - e);
    const hyperbolic = a < 0 || e >= 1;
    const semi = hyperbolic ? Math.abs(q) / 0.005 : a;
    const ecc = hyperbolic ? 0.995 : e;
    return {
      id: `comet-${id}`, name: zh, en, type: 'comet',
      radiusKm: nucleusKm / 2, nucleusKm, e: ecc, inc, year, cls, desc: note,
      hyperbolic, realE: e, realA: a,
      periodYr: periodYr || 0,
      perihelionAu: Math.abs(q),
      massKg: (4 / 3) * Math.PI * Math.pow(nucleusKm * 500, 3) * 600,
      gravity: 1e-4,
      orbit: {
        a: semi, e: ecc, inc, period: Math.pow(semi, 1.5) * 365.25,
        node: (i * 137.508) % 360, peri: (i * 97.3) % 360, M0: (i * 57.3) % 360,
      },
      spin: '自由自转',
      ui: '#9fe0e8',
    };
  });
}
