/** 外观族：小卫星共用少数几套基础贴图，靠材质颜色区分，避免一百多张程序化贴图 */
export const MOON_FAMILY = {
  rock: { base: [0.52, 0.50, 0.47], craters: 190, roughness: 0.92 },
  ice: { base: [0.74, 0.77, 0.80], craters: 150, ice: 0.6, roughness: 0.62 },
  dark: { base: [0.34, 0.32, 0.31], craters: 220, roughness: 0.96 },
  rust: { base: [0.58, 0.46, 0.36], craters: 170, lineae: 40, roughness: 0.86 },
};

const GOLDEN = 137.508;
/** 由紧凑表展开成完整的天体条目 */
export function buildMoonEntries() {
  return NAMED_MOONS.map((row, i) => {
    const [id, name, en, radiusKm, a, period, e, inc, fam, frame] = row;
    const base = MOON_FAMILY[fam] || MOON_FAMILY.rock;
    // 相位按黄金角铺开：同族卫星在轨道上均匀分布，不会挤成一堆
    const node = (i * GOLDEN) % 360;
    const M0 = (i * GOLDEN * 1.7) % 360;
    return {
      id, parent: null, name, en, type: 'moon', radiusKm,
      massKg: (4 / 3) * Math.PI * Math.pow(radiusKm * 1000, 3) * 2600,   // 以 2.6 g/cm³ 估算
      gravity: 6.674e-11 * ((4 / 3) * Math.PI * Math.pow(radiusKm * 1000, 3) * 2600) / Math.pow(radiusKm * 1000, 2),
      orbit: {
        a, period, e, inc, M0,
        node: frame === 'ec' ? node : 0,
        peri: 0,
        ...(frame === 'ec' ? { frame: 'ecliptic' } : {}),
      },
      spin: 'tidally-locked',
      ui: rgbOf(base.base),
      rock: { seed: 1000 + i * 37, ...base },
      fam,
      desc: '',
    };
  });
}

function rgbOf([r, g, b]) {
  const h = v => Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, '0');
  return `#${h(r)}${h(g)}${h(b)}`;
}
